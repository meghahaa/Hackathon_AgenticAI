"""Writes requirements.lock = `pip freeze` of the current (working) venv, minus the packages installed outside it:

  * llm-guard       - requirements-guard.txt, installed with --no-deps (its pins conflict with requirements.txt)
  * en_core_web_sm  - `python -m spacy download en_core_web_sm` (a GitHub wheel, not on PyPI)

A package that is only pulled in through platform-conditional requirements (e.g. pywin32 via
`mcp -> pywin32; sys_platform == 'win32'`) keeps that marker, so a lock frozen on Windows also installs on
Linux/macOS. Platform-only deps of the other OS (e.g. torch's CUDA wheels on Linux) are not in the freeze and
are resolved by pip there.
Run:  python scripts/freeze_lock.py      (from the activated venv, after `pip check` shows only llm-guard's pins)
"""
from __future__ import annotations

import re
import subprocess
import sys
from collections import defaultdict
from importlib.metadata import distributions
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
EXCLUDE = ("llm-guard", "en_core_web_sm")
PLATFORM_RE = re.compile(r"sys_platform|platform_system|os_name")


def platform_markers() -> dict[str, str]:
    """name -> marker, for installed packages whose every incoming (non-extra) requirement is platform-conditional."""
    edges: dict[str, list[str | None]] = defaultdict(list)
    for dist in distributions():
        for spec in dist.requires or []:
            req = Requirement(spec)
            marker = str(req.marker) if req.marker else None
            if marker and "extra" in marker:
                continue
            edges[canonicalize_name(req.name)].append(marker)
    top_level = {canonicalize_name(Requirement(line.split("#")[0].strip()).name)
                 for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines()
                 if line.split("#")[0].strip()}
    return {name: " or ".join(f"({m})" for m in sorted(set(ms)))
            for name, ms in edges.items()
            if name not in top_level and all(m and PLATFORM_RE.search(m) for m in ms)}


def main() -> None:
    cmd = [sys.executable, "-m", "pip", "freeze", "--exclude-editable"]
    for name in EXCLUDE:
        cmd += ["--exclude", name]
    frozen = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout.splitlines()
    markers = platform_markers()
    lines, marked = [], 0
    for line in frozen:
        name = canonicalize_name(re.split(r"[=@ ]", line, maxsplit=1)[0])
        marked += name in markers
        lines.append(f"{line} ; {markers[name]}" if name in markers else line)
    header = (f"# Generated by scripts/freeze_lock.py (pip freeze, Python {sys.version_info.major}."
              f"{sys.version_info.minor}, {sys.platform}); do not edit by hand.\n"
              f"# Excluded: {', '.join(EXCLUDE)} (install llm-guard with: pip install --no-deps -r "
              f"requirements-guard.txt; the spaCy model with: python -m spacy download en_core_web_sm)\n")
    (ROOT / "requirements.lock").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote requirements.lock ({len(lines)} packages, {marked} with platform markers)")


if __name__ == "__main__":
    main()
